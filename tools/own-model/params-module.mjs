// Makes the text of js/own-params.js (the shipped, synthetic-only parameters) from a trained .own model, and checks it is allowed to ship.
// Rules (also checked by tests/own-guardrails.test.js): trained on the simulator only (trainedOn exactly ['sim-v1']), at most 25,000 parameters,
// at most 128 KB of file.
import { writeOwnFile, parseOwnFile } from '../../js/own-file.js';
import { SIM_VERSION } from './sim.mjs';
import { sha256OfParams } from './common.mjs';

export const BUDGET = { maxParams: 25000, maxBytes: 128 * 1024 };

// bytes of a .own file -> { ok, reason?, text? }
export function paramsModuleFrom(ownBytes) {
  const { header, params } = parseOwnFile(ownBytes);
  const ids = header.trainedOn.map(t => t.id);
  if (ids.length !== 1 || ids[0] !== SIM_VERSION) return { ok: false, reason: `Not shipped: the model was trained on ${ids.join(', ') || 'unknown data'}, and only simulator-only (${SIM_VERSION}) models may be committed.` };
  if (header.paramCount > BUDGET.maxParams) return { ok: false, reason: `Not shipped: ${header.paramCount} parameters is over the budget of ${BUDGET.maxParams}.` };
  const b64 = Buffer.from(params.buffer, params.byteOffset, params.byteLength).toString('base64');
  const body = {
    version: 1, size: header.size, seed: header.seed, simVersion: SIM_VERSION, paramCount: header.paramCount, sha256: sha256OfParams(params),
    trainedOn: [SIM_VERSION], b64
  };
  const text = `// Own model: the shipped parameters. GENERATED by \`npm run own:all\` (tools/own-model/all.mjs); do not edit by hand.\n`
    + `// Trained on simulator output only (${SIM_VERSION}); nothing here comes from real review data. The numbers are 32-bit floats, little-endian, in base64.\n`
    + `export const OWN_PARAMS = ${JSON.stringify(body, null, 2)};\n`;
  if (text.length > BUDGET.maxBytes) return { ok: false, reason: `Not shipped: the file would be ${text.length} bytes, over the budget of ${BUDGET.maxBytes}.` };
  return { ok: true, text, body };
}

// the same parameters as a .own file (used by tests)
export const ownBytesFromParams = (size, params, trainedOn = [{ id: SIM_VERSION, licence: 'ours' }]) => writeOwnFile({ size, params, trainedOn, seed: 1, gitStamp: 'test' });
